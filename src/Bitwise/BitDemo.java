package Bitwise;

public class BitDemo {
    public static void main(String[] args) {
        int a = 2, b = 4;

        System.out.println(a&b);
        System.out.println(a | b);
        System.out.println(a ^ b);
        System.out.println(~a);
        System.out.println(a << 1);
        System.out.println(a >> 1);
    }
}
